/**
 * RuleEngine — Generic Business Rules DSL
 *
 * Transforms structured rule definitions into Express middleware,
 * route guards, and database logic for ANY exam problem.
 *
 * Rules are NOT exam-specific. They work for:
 *   Voting/Elections, Library, Payroll, Clinic, Inventory, Students, etc.
 *
 * Rule types:
 *   preCheck   — Check condition before INSERT/UPDATE/DELETE
 *   postAction — UPDATE another table after INSERT/UPDATE/DELETE
 *   limitCheck — Prevent exceeding a limit per group
 *   computed   — SQL computation column for reports
 *   rank       — Ranking/window function for reports
 *
 * Usage:
 *   const rules = new RuleEngine(schemaRegistry);
 *   const middlewareCode = rules.generateMiddleware([
 *     { type: 'preCheck', ... },
 *     { type: 'limitCheck', ... }
 *   ]);
 */
class RuleEngine {
    constructor(schemaRegistry) {
        this.schemaRegistry = schemaRegistry;
    }

    /**
     * Generate validators, post-actions and the per-table guards that wire them
     * onto the CRUD routes. Must be emitted after express.json() and authenticate,
     * and before the CRUD routes.
     * @param {Array} rules - Array of rule definition objects
     * @returns {string} Generated JavaScript code
     */
    generateAll(rules) {
        if (!rules || rules.length === 0) {
            return '// No business rules defined\n';
        }
        const checks = rules.filter(r => r.type === 'preCheck' || r.type === 'limitCheck');
        const posts = rules.filter(r => r.type === 'postAction');

        let code = '';
        code += '// ============================================================\n';
        code += '// Business Rules — auto-generated by RuleEngine\n';
        code += '// ============================================================\n\n';
        code += 'function _runWithRules(req, write) {\n';
        code += '  return db.transaction(() => {\n';
        code += '    const result = write();\n';
        code += '    if (result.changes > 0) (req._postActions || []).forEach(action => action(req));\n';
        code += '    return result;\n';
        code += '  })();\n';
        code += '}\n\n';

        code += '// Which operation a request under /api/<table> performs\n';
        code += 'function _ruleOp(req) {\n';
        code += "  const parts = req.path.split('/').filter(Boolean);\n";
        code += "  if (req.method === 'POST') return parts.length === 0 ? 'INSERT' : (parts[1] === 'delete' ? 'DELETE' : null);\n";
        code += "  if (req.method === 'PUT' || req.method === 'PATCH') return parts.length === 1 ? 'UPDATE' : (parts[1] === 'activate' ? 'ACTIVATE' : null);\n";
        code += "  if (req.method === 'DELETE') return parts.length === 1 ? 'DELETE' : null;\n";
        code += '  return null;\n';
        code += '}\n\n';

        const groups = new Map();
        const loose = [];
        for (const r of checks) {
            if (!r.targetTable) { loose.push(r); continue; }
            const key = r.targetTable + '|' + this._ruleAction(r);
            if (!groups.has(key)) groups.set(key, []);
            groups.get(key).push(r);
        }
        const fnName = key => {
            const [t, o] = key.split('|');
            return 'validate' + t.charAt(0).toUpperCase() + t.slice(1) + o.charAt(0) + o.slice(1).toLowerCase();
        };
        for (const [key, list] of groups) code += this._generateValidator(fnName(key), list) + '\n';
        if (loose.length > 0) {
            code += '// Rules without a targetTable: attach by hand, e.g. app.post(path, validateBusinessRules, handler)\n';
            code += this._generateValidator('validateBusinessRules', loose) + '\n';
        }
        posts.forEach((r, i) => { code += this._generatePostAction(r, i) + '\n'; });

        const tables = [...new Set([...groups.keys()].map(k => k.split('|')[0]).concat(posts.map(r => r.targetTable).filter(Boolean)))];
        for (const t of tables) {
            const pk = this._getPK(t);
            code += `// Rules for /api/${t.toLowerCase()}\n`;
            code += `app.use('/api/${t.toLowerCase()}', (req, res, next) => {\n`;
            code += '  const op = _ruleOp(req);\n';
            code += '  if (!op) return next();\n';
            code += '  try {\n';
            code += `    const cur = op === 'INSERT' ? null : db.prepare(${JSON.stringify(`SELECT * FROM ${t} WHERE ${pk} = ?`)}).get(req.path.split('/').filter(Boolean)[0]);\n`;
            code += '    req._ruleBody = Object.assign({}, cur, req.body);\n';
            code += '  } catch (err) {\n';
            code += '    return next(err);\n';
            code += '  }\n';
            posts.forEach((r, i) => {
                if (r.targetTable === t) code += `  if (op === '${this._ruleAction(r)}') (req._postActions || (req._postActions = [])).push(postAction${i});\n`;
            });
            for (const key of groups.keys()) {
                if (key.split('|')[0] === t) code += `  if (op === '${key.split('|')[1]}') return ${fnName(key)}(req, res, next);\n`;
            }
            code += '  next();\n';
            code += '});\n\n';
        }

        code += '// ============================================================\n';
        code += '// End of Business Rules\n';
        code += '// ============================================================\n';

        return code;
    }

    /**
     * Generate a SQL query with computed columns for reports.
     * @param {Array} baseColumns - Array of { table, field, aggregate }
     * @param {Array} computedColumns - Array of { name, expression, type }
     * @param {Array} rankColumns - Array of { name, partitionTable, partitionField, orderTable, orderField, orderDir }
     * @param {Array} filters, sortBy, limit, groupBy, having, distinct, joinType
     * @returns {string} SQL query string
     */
    generateReportSql(baseColumns, computedColumns, rankColumns, filters, sortBy, limit, groupBy, having, distinct, joinType) {
        const { QueryGenerator } = require('./queryGenerator');
        const qg = new QueryGenerator(this.schemaRegistry);

        // Use the queryGenerator's generateReportSql for consistency
        // This delegates to the shared implementation in QueryGenerator to avoid duplication
        return qg.generateReportSql(baseColumns, computedColumns, filters, sortBy, limit, groupBy, having, distinct, joinType);
    }

    /**
     * Generate a complete report HTML page with computed columns, percentages, and rankings.
     * @param {string} reportName - Name for the report
     * @param {Array} displayColumns - What columns to display { label, field, format, highlight }
     * @returns {string} Complete HTML page
     */
    generateReportHtml(reportName, displayColumns, options = {}) {
        const { QueryGenerator } = require('./queryGenerator');
        const query = this.schemaRegistry.getQuery?.(reportName);
        return new QueryGenerator(this.schemaRegistry).generateReportHtml(reportName, query?.columns || [], displayColumns, options);
    }

    /**
     * Generate Express server route for a report with computed columns.
     * @param {string} reportName
     * @param {Array} baseColumns
     * @param {Array} computedColumns
     * @param {Array} rankColumns
     * @param {Array} filters, sortBy, limit, groupBy, having, distinct, joinType
     * @returns {string} Server route code
     */
    generateReportServer(reportName, baseColumns, computedColumns, rankColumns, filters, sortBy, limit, groupBy, having, distinct, joinType) {
        const sql = this.generateReportSql(baseColumns, computedColumns, rankColumns, filters, sortBy, limit, groupBy, having, distinct, joinType);
        const route = `/api/${reportName}`;
        const varName = `report${reportName.charAt(0).toUpperCase() + reportName.slice(1)}`;

        let code = '';
        code += '// --- Report: ' + reportName + ' ---\n';
        // Escape SQL for template literal
        const escapedSql = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
        code += 'const ' + varName + 'Sql = `' + escapedSql + '`;\n\n';
        code += "app.get('" + route + "', authenticate, (req, res) => {\n";
        code += '  try {\n';
        code += '    const rows = db.prepare(' + varName + 'Sql).all();\n';
        code += '    res.json(rows);\n';
        code += '  } catch (err) {\n';
        code += '    res.status(500).json({ error: err.message });\n';
        code += '  }\n';
        code += '});\n';
        return code;
    }

    // ======================= Internal Helpers =======================

    /** Operation a rule applies to; DEACTIVATE is the soft-delete DELETE route. */
    _ruleAction(rule) {
        const a = String(rule.action || 'INSERT').toUpperCase();
        return a === 'DEACTIVATE' ? 'DELETE' : a;
    }

    /** Column of checkTable the request row points at, and the body field holding its value. */
    _linkField(targetTable, checkTable, field) {
        const t = targetTable && this.schemaRegistry.getTable(targetTable);
        const fk = t && (t.fields || []).find(f => f.fk && f.fk.table === checkTable && (!field || f.name === field));
        if (fk) return { col: fk.fk.field || this._getPK(checkTable), src: fk.name };
        const id = field || this._inferIdentityField(checkTable);
        return { col: id, src: id };
    }

    /**
     * Validator for preCheck/limitCheck rules. Reads req._ruleBody (request body
     * merged over the existing row) so update/delete checks see every field.
     */
    _generateValidator(name, rules) {
        const b = f => `body[${JSON.stringify(f)}]`;
        let code = `function ${name}(req, res, next) {\n`;
        code += '  try {\n';
        code += '    const body = req._ruleBody || req.body || {};\n';
        code += '    const errors = [];\n';
        rules.forEach((rule, i) => {
            if (rule.type === 'limitCheck') {
                const msg = rule.errorMessage || `Cannot exceed ${rule.limitField} limit`;
                const limitPK = this._getPK(rule.limitTable);
                code += `    const count${i} = db.prepare(${JSON.stringify(`SELECT COUNT(*) AS cnt FROM ${rule.targetTable} WHERE ${rule.groupField} = ?`)}).get(${b(rule.groupField)});\n`;
                code += `    const limit${i} = db.prepare(${JSON.stringify(`SELECT ${rule.limitField} AS lim FROM ${rule.limitTable} WHERE ${limitPK} = ?`)}).get(${b(rule.groupField)});\n`;
                code += `    if (limit${i} && count${i}.cnt >= limit${i}.lim) errors.push(${JSON.stringify(msg)});\n`;
                return;
            }
            const msg = rule.errorMessage || `Business rule violation: ${rule.checkTable}.${rule.checkField} check failed`;
            if (rule.operator === 'EXISTS') {
                const sql = `SELECT 1 FROM ${rule.checkTable} WHERE ${rule.condition || `${rule.checkTable}.${rule.checkField} = ?`}`;
                const params = rule.condition ? '' : b(rule.field || rule.checkField);
                code += `    if (!db.prepare(${JSON.stringify(sql)}).get(${params})) errors.push(${JSON.stringify(msg)});\n`;
            } else {
                const { col, src } = this._linkField(rule.targetTable, rule.checkTable, rule.field);
                const op = rule.operator || '=';
                if (!['=', '!=', '<', '>', '<=', '>=', 'LIKE', 'IS NULL', 'IS NOT NULL'].includes(op)) throw new Error(`Unsupported rule operator: ${op}`);
                const unary = op === 'IS NULL' || op === 'IS NOT NULL';
                const sql = `SELECT 1 FROM ${rule.checkTable} WHERE ${col} = ? AND ${rule.checkField} ${op}${unary ? '' : ' ?'}`;
                code += `    if (!db.prepare(${JSON.stringify(sql)}).get(${b(src)}${unary ? '' : ', ' + JSON.stringify(rule.checkValue ?? null)})) errors.push(${JSON.stringify(msg)});\n`;
            }
        });
        code += "    if (errors.length > 0) return res.status(403).json({ error: errors.join('; ') });\n";
        code += '    next();\n';
        code += '  } catch (err) {\n';
        code += '    res.status(500).json({ error: err.message });\n';
        code += '  }\n';
        code += '}\n';
        return code;
    }

    /** Post-action, run by the table guard once the response succeeded. */
    _generatePostAction(rule, i) {
        const sql = `UPDATE ${rule.setTable} SET ${rule.setField} = ${this._sqlValueExpr(rule.setValue)} WHERE ${rule.whereField} = ?`;
        let code = `// After ${this._ruleAction(rule)} on ${rule.targetTable}: sets ${rule.setTable}.${rule.setField}\n`;
        code += `function postAction${i}(req) {\n`;
        code += `  db.prepare(${JSON.stringify(sql)}).run((req._ruleBody || req.body || {})[${JSON.stringify(rule.whereSourceField || rule.whereField)}]);\n`;
        code += '}\n';
        return code;
    }

    /**
     * setValue is typed as SQL in the rule editor. Keep numbers, quoted strings,
     * NULL, CURRENT_* and column arithmetic (votes + 1) as-is; quote bare words.
     */
    _sqlValueExpr(val) {
        const s = String(val == null ? '' : val).trim();
        if (/^(-?\d+(\.\d+)?|NULL|CURRENT_(TIMESTAMP|DATE|TIME)|'(?:[^']|'')*')$/i.test(s)) return s;
        if (/^[A-Za-z_]\w*\s*[-+*/]\s*-?\d+(?:\.\d+)?$/.test(s)) return s;
        return this._quoteSqlValue(s);
    }

    /** Scalar expression correlated to the target row, usable in SELECT/UPDATE. */
    generateFormulaSql(targetTable, operands, operator = '-') {
        if (!operands || operands.length < 2) return null;
        if (!['+', '-', '*', '/'].includes(operator)) throw new Error('Unsupported formula operator');
        if (!this.schemaRegistry.getTable(targetTable)) return null;
        const quote = name => '"' + String(name).replace(/"/g, '""') + '"';
        const joins = [];
        const aliases = new Map([[targetTable, 'r0']]);
        const queue = [targetTable];
        while (queue.length) {
            const from = queue.shift();
            for (const field of this.schemaRegistry.getTable(from).fields) {
                if (!field.fk || aliases.has(field.fk.table)) continue;
                if (!this.schemaRegistry.getTable(field.fk.table)) continue;
                const alias = 'r' + aliases.size;
                aliases.set(field.fk.table, alias);
                joins.push(`LEFT JOIN ${quote(field.fk.table)} ${alias} ON ${aliases.get(from)}.${quote(field.name)} = ${alias}.${quote(field.fk.field || this._getPK(field.fk.table))}`);
                queue.push(field.fk.table);
            }
        }
        const expr = operands.map(operand => {
            if (!aliases.has(operand.table)) throw new Error(`No foreign-key path to ${operand.table}`);
            if (!this.schemaRegistry.getTable(operand.table).fields.some(f => f.name === operand.field)) throw new Error(`Unknown formula field ${operand.field}`);
            return `${aliases.get(operand.table)}.${quote(operand.field)}`;
        }).join(` ${operator} `);
        const pk = quote(this._getPK(targetTable));
        return `(SELECT ${expr} FROM ${quote(targetTable)} r0 ${joins.join(' ')} WHERE r0.${pk} = ${quote(targetTable)}.${pk})`;
    }

    /**
     * Expand a computed column expression into SQL.
     * Supports: percentage, runningTotal, rank, formula
     */
    _expandComputedExpression(expression, column) {
        if (expression === 'percentage') {
            // COUNT / SUM OVER for percentage of total
            const countExpr = column.aggregate
                ? `${column.aggregate.toUpperCase()}(${column.sourceTable}.${column.sourceField})`
                : `COUNT(${column.sourceTable}.${column.sourceField})`;
            const totalExpr = column.partitionField
                ? `SUM(${countExpr}) OVER (PARTITION BY ${column.partitionTable}.${column.partitionField})`
                : `SUM(${countExpr}) OVER ()`;
            return `ROUND(CAST(${countExpr} AS REAL) / NULLIF(${totalExpr}, 0) * 100, 2)`;
        }

        if (expression === 'runningTotal') {
            const orderBy = column.orderField
                ? `ORDER BY ${column.orderTable}.${column.orderField}`
                : '';
            const partitionBy = column.partitionField
                ? `PARTITION BY ${column.partitionTable}.${column.partitionField} `
                : '';
            return `SUM(${column.sourceTable}.${column.sourceField}) OVER (${partitionBy}${orderBy})`;
        }

        if (expression === 'rank') {
            const orderExpr = `${column.orderTable}.${column.orderField} ${column.orderDir || 'DESC'}`;
            const partitionExpr = column.partitionField
                ? `PARTITION BY ${column.partitionTable}.${column.partitionField} `
                : '';
            const func = column.rankFunction || 'DENSE_RANK';
            return `${func}() OVER (${partitionExpr}ORDER BY ${orderExpr})`;
        }

        // Custom formula — return as-is
        return expression;
    }

    /**
     * Resolve JOINs between tables using FK relationships.
     */
    _resolveJoins(tableNames, joinType) {
        const joinT = joinType || 'LEFT';
        const tableObjs = tableNames
            .map(t => ({ name: t, table: this.schemaRegistry.getTable(t) }))
            .filter(t => t.table);

        // Collect outgoing FK references
        const outgoingFKs = {};
        for (const tObj of tableObjs) {
            const fks = [];
            for (const f of (tObj.table.fields || [])) {
                if (f.fk && tableNames.includes(f.fk.table)) {
                    fks.push({ fromField: f.name, targetTable: f.fk.table, targetField: f.fk.field });
                }
            }
            outgoingFKs[tObj.name] = fks;
        }

        // Collect incoming FK references
        const incomingFKs = {};
        for (const tName of tableNames) {
            incomingFKs[tName] = [];
            for (const [otherName, fks] of Object.entries(outgoingFKs)) {
                for (const fk of fks) {
                    if (fk.targetTable === tName) {
                        incomingFKs[tName].push({ fromTable: otherName, fromField: fk.fromField, targetField: fk.targetField });
                    }
                }
            }
        }

        // Main table = the one with the most outgoing FKs
        let mainTable = tableNames[0];
        let maxOutgoing = 0;
        for (const [tName, fks] of Object.entries(outgoingFKs)) {
            if (fks.length > maxOutgoing) {
                maxOutgoing = fks.length;
                mainTable = tName;
            }
        }

        const joins = [];
        const joinedTables = new Set([mainTable]);
        const queue = [mainTable];

        while (queue.length > 0) {
            const currentTable = queue.shift();
            // Outgoing FKs
            for (const fk of (outgoingFKs[currentTable] || [])) {
                if (!joinedTables.has(fk.targetTable)) {
                    joins.push(`${joinT} JOIN ${fk.targetTable} ON ${currentTable}.${fk.fromField} = ${fk.targetTable}.${fk.targetField}`);
                    joinedTables.add(fk.targetTable);
                    queue.push(fk.targetTable);
                }
            }
            // Incoming FKs
            for (const fk of (incomingFKs[currentTable] || [])) {
                if (!joinedTables.has(fk.fromTable)) {
                    joins.push(`${joinT} JOIN ${fk.fromTable} ON ${currentTable}.${fk.targetField} = ${fk.fromTable}.${fk.fromField}`);
                    joinedTables.add(fk.fromTable);
                    queue.push(fk.fromTable);
                }
            }
        }

        // CROSS JOIN any remaining tables
        for (const tName of tableNames) {
            if (!joinedTables.has(tName)) {
                joins.push(`CROSS JOIN ${tName}`);
                joinedTables.add(tName);
            }
        }

        return { mainTable, joins };
    }

    _inferIdentityField(tableName) {
        const table = this.schemaRegistry.getTable(tableName);
        if (!table || !table.fields) return null;
        // Look for common identity patterns
        for (const f of table.fields) {
            const lower = f.name.toLowerCase();
            if (lower === 'id' || lower.endsWith('id') || lower.endsWith('no')) {
                return f.name;
            }
        }
        // Fallback to first non-PK field
        const firstNonPK = table.fields.find(f => !f.pk);
        return firstNonPK ? firstNonPK.name : (table.fields[0] ? table.fields[0].name : 'id');
    }

    _getPK(tableName) {
        const table = this.schemaRegistry.getTable(tableName);
        if (!table) return 'id';
        const pk = table.fields.find(f => f.pk);
        return pk ? pk.name : (table.fields[0]?.name || 'id');
    }

    _quoteSqlValue(val) {
        if (val === null || val === undefined) return 'NULL';
        const str = String(val);
        if (/^-?\d+(\.\d+)?$/.test(str)) return str;
        return "'" + str.replace(/'/g, "''") + "'";
    }
}

module.exports = { RuleEngine };
